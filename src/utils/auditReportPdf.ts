import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';
import { FinancialAuditReport } from '../types/crm';

const formatNgnPdf = (amount: number): string => {
  const num = Math.round(Number(amount || 0));
  const prefix = num < 0 ? '-NGN ' : 'NGN ';
  return `${prefix}${Math.abs(num).toLocaleString('en-US')}`;
};

export const downloadForensicReportPdf = (report: FinancialAuditReport) => {
  const doc = new jsPDF({ orientation: 'portrait', unit: 'pt', format: 'a4' });
  const pageWidth = doc.internal.pageSize.getWidth();
  const marginX = 40;
  let y = 44;

  // Branded Executive Header Band
  doc.setFillColor(24, 114, 245);
  doc.rect(0, 0, pageWidth, 86, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.text('FORENSIC FINANCIAL AUDIT & RECONCILIATION REPORT', marginX, 34);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.text(`${report.reportCode}  |  ${report.title}`, marginX, 52);
  doc.setFontSize(8.5);
  doc.text(
    `Period: ${report.periodLabel}   •   Generated By: ${report.generatedBy}   •   Date: ${new Date(report.generatedAt).toLocaleString()}`,
    marginX,
    68
  );

  y = 108;

  // Executive KPI Strip
  const mf = report.scanSnapshot?.moneyFlow;
  const gap = Number(mf?.cashReconciliationGap || 0);
  const kpis = [
    { label: 'Audit Health', value: `${report.scanSnapshot?.healthScore ?? 100}%` },
    { label: 'Student Inflows', value: formatNgnPdf(mf?.totalStudentPaymentsReceived || 0) },
    { label: 'Actual Company Cash', value: formatNgnPdf(mf?.actualCompanyCashTotal || 0) },
    { label: 'Master Cash Gap', value: formatNgnPdf(gap) },
  ];

  const boxW = (pageWidth - marginX * 2 - 24) / 4;
  kpis.forEach((k, idx) => {
    const x = marginX + idx * (boxW + 8);
    doc.setFillColor(244, 247, 248);
    doc.setDrawColor(217, 230, 232);
    doc.roundedRect(x, y, boxW, 46, 6, 6, 'FD');
    doc.setTextColor(100, 116, 139);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(7.5);
    doc.text(k.label.toUpperCase(), x + 8, y + 16);
    doc.setTextColor(15, 23, 42);
    doc.setFontSize(10.5);
    doc.text(k.value, x + 8, y + 34);
  });

  y += 64;

  // Executive Summary
  doc.setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.text('1. Executive Summary', marginX, y);
  y += 14;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(51, 65, 85);
  const summaryLines = doc.splitTextToSize(report.executiveSummary || 'No summary available.', pageWidth - marginX * 2);
  doc.text(summaryLines, marginX, y);
  y += summaryLines.length * 12 + 10;

  if (report.aiNarrative) {
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(9.5);
    doc.setTextColor(24, 114, 245);
    doc.text('AI Forensic Narrative', marginX, y);
    y += 13;
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8.8);
    doc.setTextColor(51, 65, 85);
    const aiLines = doc.splitTextToSize(report.aiNarrative, pageWidth - marginX * 2);
    doc.text(aiLines, marginX, y);
    y += aiLines.length * 11.5 + 12;
  }

  // 2. 5-Layer Money Flow Reconciliation Table
  doc.setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.text('2. 5-Layer Money-Flow Reconciliation', marginX, y);
  y += 8;

  autoTable(doc, {
    startY: y,
    margin: { left: marginX, right: marginX },
    head: [['Financial Layer / Metric', 'Amount (NGN)']],
    body: [
      ['L1 • Tuition Billed (CRM Students)', formatNgnPdf(mf?.totalTuitionBilled || 0)],
      ['L1 • Unexempted Course Price Variance Exposure', formatNgnPdf(mf?.coursePriceVarianceTotal || 0)],
      ['L2 • Student Payments Recorded in CRM', formatNgnPdf(mf?.totalStudentPaymentsReceived || 0)],
      ['L2 • Verified Account Inflows (Paystack + Bank Statements)', formatNgnPdf(mf?.totalWalletInflow || 0)],
      ['L3 • 37% Mentor Commissions Due (Agreed)', formatNgnPdf(mf?.totalAgreedCommissionDue || 0)],
      ['L3 • Mentor Commissions Disbursed', formatNgnPdf(mf?.totalDisbursedToMentors || 0)],
      ['L4 • Non-Mentor Business OpEx Paid', formatNgnPdf(mf?.totalNonMentorExpensesPaid || 0)],
      ['L5 • Expected Net Cash Position (Inflows - Mentors - OpEx)', formatNgnPdf(mf?.expectedNetCashPosition || 0)],
      ['L5 • Actual Company Cash (Paystack + External Banks)', formatNgnPdf(mf?.actualCompanyCashTotal || 0)],
      ['L5 • Master Cash Reconciliation Gap (Actual - Expected)', formatNgnPdf(gap)],
    ],
    theme: 'grid',
    headStyles: { fillColor: [24, 114, 245], textColor: 255, fontSize: 8.5, fontStyle: 'bold' },
    bodyStyles: { fontSize: 8.5, textColor: [30, 41, 59] },
    columnStyles: { 1: { halign: 'right', fontStyle: 'bold' } },
  });

  y = ((doc as any).lastAutoTable?.finalY || y + 140) + 18;

  // 3. Company Bank Account Snapshots
  if (report.bankSnapshots && report.bankSnapshots.length > 0) {
    if (y > 680) {
      doc.addPage();
      y = 44;
    }
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11);
    doc.setTextColor(15, 23, 42);
    doc.text('3. Company Bank Account Snapshots', marginX, y);
    y += 8;

    autoTable(doc, {
      startY: y,
      margin: { left: marginX, right: marginX },
      head: [['Bank', 'NUBAN', 'Account Name', 'As-Of Date', 'Closing Balance']],
      body: report.bankSnapshots.map((b) => [
        b.bankName,
        b.accountNumber,
        b.accountName,
        b.asOfDate,
        formatNgnPdf(b.closingBalance),
      ]),
      theme: 'grid',
      headStyles: { fillColor: [2, 132, 199], textColor: 255, fontSize: 8 },
      bodyStyles: { fontSize: 8, textColor: [30, 41, 59] },
      columnStyles: { 4: { halign: 'right', fontStyle: 'bold' } },
    });

    y = ((doc as any).lastAutoTable?.finalY || y + 80) + 18;
  }

  // 4. Flagged Discrepancies
  if (y > 650) {
    doc.addPage();
    y = 44;
  }
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(15, 23, 42);
  doc.text(`4. Flagged Discrepancies (${report.findingsSnapshot?.length || 0})`, marginX, y);
  y += 8;

  autoTable(doc, {
    startY: y,
    margin: { left: marginX, right: marginX },
    head: [['Layer', 'Severity', 'Finding', 'Expected', 'Actual', 'Delta', 'Status']],
    body: (report.findingsSnapshot || []).map((f) => [
      `L${f.layer || '-'}`,
      f.severity,
      `${f.title}\n${f.ruleCode}`,
      formatNgnPdf(f.expectedAmount),
      formatNgnPdf(f.actualAmount),
      formatNgnPdf(f.deltaAmount),
      f.status,
    ]),
    theme: 'striped',
    headStyles: { fillColor: [220, 38, 38], textColor: 255, fontSize: 7.5 },
    bodyStyles: { fontSize: 7.5, textColor: [30, 41, 59] },
    columnStyles: {
      2: { cellWidth: 185 },
      3: { halign: 'right' },
      4: { halign: 'right' },
      5: { halign: 'right', fontStyle: 'bold' },
    },
  });

  // 5. Investigation Cases & User Responses
  if (report.casesSnapshot && report.casesSnapshot.length > 0) {
    y = ((doc as any).lastAutoTable?.finalY || y + 80) + 18;
    if (y > 680) {
      doc.addPage();
      y = 44;
    }
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11);
    doc.setTextColor(15, 23, 42);
    doc.text(`5. Investigation Cases & User Responses (${report.casesSnapshot.length})`, marginX, y);
    y += 8;

    autoTable(doc, {
      startY: y,
      margin: { left: marginX, right: marginX },
      head: [['Case #', 'Title', 'Status', 'Exposure', 'User Queries']],
      body: report.casesSnapshot.map((c) => [
        c.caseNumber,
        c.title,
        c.status,
        formatNgnPdf(c.totalExposureNaira),
        c.queries.length === 0
          ? 'No queries sent'
          : c.queries.map((q) => `${q.targetUserName}: ${q.responseText || 'Pending'}`).join('\n'),
      ]),
      theme: 'grid',
      headStyles: { fillColor: [124, 58, 237], textColor: 255, fontSize: 8 },
      bodyStyles: { fontSize: 7.5, textColor: [30, 41, 59] },
      columnStyles: { 3: { halign: 'right', fontStyle: 'bold' } },
    });
  }

  // Page numbers footer on every page
  const totalPages = doc.getNumberOfPages();
  for (let p = 1; p <= totalPages; p++) {
    doc.setPage(p);
    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184);
    doc.text(
      `Confidential — Educate CRM Super Admin Financial Audit (${report.reportCode})   |   Page ${p} of ${totalPages}`,
      marginX,
      doc.internal.pageSize.getHeight() - 22
    );
  }

  doc.save(`${report.reportCode}-forensic-audit-report.pdf`);
};
