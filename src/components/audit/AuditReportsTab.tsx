import React, { useEffect, useMemo, useState } from 'react';
import { formatNaira, useCRM } from '../../context/CRMContext';
import { FinancialAuditReport } from '../../types/crm';
import { downloadForensicReportPdf } from '../../utils/auditReportPdf';
import { SectionCard } from '../common/KineticUI';

const escapeCsv = (val: unknown) => {
  const s = String(val ?? '');
  if (s.includes(',') || s.includes('"') || s.includes('\n')) {
    return `"${s.replace(/"/g, '""')}"`;
  }
  return s;
};

export const AuditReportsTab: React.FC = () => {
  const {
    financialAuditReports,
    generateFinancialAuditReport,
    deleteFinancialAuditReport,
  } = useCRM();

  const [selectedReportId, setSelectedReportId] = useState<string | null>(null);
  const [title, setTitle] = useState('');
  const [periodLabel, setPeriodLabel] = useState(
    `As of ${new Date().toLocaleDateString('en-NG', { year: 'numeric', month: 'short', day: 'numeric' })}`
  );
  const [includeResolved, setIncludeResolved] = useState(false);
  const [isGenerating, setIsGenerating] = useState(false);
  const [findingsPage, setFindingsPage] = useState(1);
  const findingsPageSize = 10;

  const selectedReport: FinancialAuditReport | null = useMemo(() => {
    const id = selectedReportId || financialAuditReports[0]?.id || null;
    return financialAuditReports.find((r) => r.id === id) || null;
  }, [financialAuditReports, selectedReportId]);

  useEffect(() => {
    setFindingsPage(1);
  }, [selectedReport?.id]);

  const handleGenerate = async (e: React.FormEvent) => {
    e.preventDefault();
    setIsGenerating(true);
    try {
      const created = await generateFinancialAuditReport({
        title: title.trim() || undefined,
        periodLabel: periodLabel.trim() || undefined,
        includeResolved,
      });
      if (created) {
        setSelectedReportId(created.id);
        setTitle('');
      }
    } finally {
      setIsGenerating(false);
    }
  };

  const handleExportCsv = (report: FinancialAuditReport) => {
    const mf = report.scanSnapshot?.moneyFlow;
    const rows: string[][] = [
      ['Report Code', report.reportCode],
      ['Title', report.title],
      ['Period', report.periodLabel],
      ['Generated By', report.generatedBy],
      ['Generated At', report.generatedAt],
      ['Audit Health Score', `${report.scanSnapshot?.healthScore ?? 100}%`],
      [],
      ['--- 5-LAYER MONEY FLOW RECONCILIATION ---', 'Amount (NGN)'],
      ['Tuition Billed', String(mf?.totalTuitionBilled || 0)],
      ['Course Price Variance Exposure', String(mf?.coursePriceVarianceTotal || 0)],
      ['Student Payments Received', String(mf?.totalStudentPaymentsReceived || 0)],
      ['37% Expected Commission', String(mf?.totalExpectedCommission37 || 0)],
      ['Agreed Mentor Commission Due', String(mf?.totalAgreedCommissionDue || 0)],
      ['Disbursed to Mentors', String(mf?.totalDisbursedToMentors || 0)],
      ['Non-Mentor Business Expenses Paid', String(mf?.totalNonMentorExpensesPaid || 0)],
      ['Paystack Live Balance', String(mf?.paystackLiveBalance || 0)],
      ['External Nigerian Bank Balances', String(mf?.externalBankBalancesTotal || 0)],
      ['Actual Company Cash Total', String(mf?.actualCompanyCashTotal || 0)],
      ['Expected Net Cash Position', String(mf?.expectedNetCashPosition || 0)],
      ['Cash Reconciliation Gap', String(mf?.cashReconciliationGap || 0)],
      [],
      ['--- FLAGGED DISCREPANCIES ---'],
      ['Layer', 'Severity', 'Rule Code', 'Status', 'Entity', 'Title', 'Expected (NGN)', 'Actual (NGN)', 'Delta (NGN)', 'Diagnosis'],
      ...(report.findingsSnapshot || []).map((f) => [
        `L${f.layer || '-'}`,
        f.severity,
        f.ruleCode,
        f.status,
        f.entityName,
        f.title,
        String(f.expectedAmount || 0),
        String(f.actualAmount || 0),
        String(f.deltaAmount || 0),
        f.aiDiagnosis,
      ]),
    ];

    const csv = rows.map((r) => r.map(escapeCsv).join(',')).join('\n');
    const blob = new Blob([csv], { type: 'text/csv;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${report.reportCode}-financial-audit.csv`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const reportFindings = selectedReport?.findingsSnapshot || [];
  const findingsTotalPages = Math.max(1, Math.ceil(reportFindings.length / findingsPageSize));
  const safeFindingsPage = Math.min(findingsPage, findingsTotalPages);
  const pagedFindings = reportFindings.slice(
    (safeFindingsPage - 1) * findingsPageSize,
    safeFindingsPage * findingsPageSize
  );

  const mf = selectedReport?.scanSnapshot?.moneyFlow;
  const cashGap = Number(mf?.cashReconciliationGap || 0);

  return (
    <div className="space-y-5">
      {/* Generate New Forensic Report */}
      <div className="print:hidden">
        <SectionCard
          title="Generate & Archive Forensic Audit Report"
          subtitle="Snapshots the 5-layer reconciliation, discrepancies, bank balances, and investigation responses for management & accountants"
          icon="summarize"
        >
          <form onSubmit={handleGenerate} className="grid grid-cols-1 md:grid-cols-12 gap-3 items-end">
            <div className="md:col-span-5">
              <label className="block text-[11px] font-bold text-secondary mb-1">Report Title</label>
              <input
                type="text"
                value={title}
                onChange={(e) => setTitle(e.target.value)}
                placeholder="e.g. Q4 ERP Financial Reconciliation & Cash Audit"
                className="w-full rounded-lg border border-outline-variant bg-white px-3 py-2 text-xs text-on-surface"
              />
            </div>
            <div className="md:col-span-3">
              <label className="block text-[11px] font-bold text-secondary mb-1">Period Label</label>
              <input
                type="text"
                value={periodLabel}
                onChange={(e) => setPeriodLabel(e.target.value)}
                className="w-full rounded-lg border border-outline-variant bg-white px-3 py-2 text-xs text-on-surface"
              />
            </div>
            <div className="md:col-span-2 flex items-center h-9">
              <label className="inline-flex items-center gap-1.5 text-xs text-secondary cursor-pointer">
                <input
                  type="checkbox"
                  checked={includeResolved}
                  onChange={(e) => setIncludeResolved(e.target.checked)}
                />
                Include Resolved
              </label>
            </div>
            <div className="md:col-span-2 flex justify-end">
              <button
                type="submit"
                disabled={isGenerating}
                className="w-full inline-flex items-center justify-center gap-1.5 px-4 py-2 rounded-lg bg-primary text-white text-xs font-bold hover:bg-primary/90 disabled:opacity-50 cursor-pointer"
              >
                <span className="material-symbols-outlined text-[16px]">description</span>
                {isGenerating ? 'Saving...' : 'Generate Report'}
              </button>
            </div>
          </form>
        </SectionCard>
      </div>

      {/* Archive + Executive Report Document Viewer */}
      <div className="grid grid-cols-1 lg:grid-cols-12 gap-5">
        {/* Saved Archive List */}
        <div className="lg:col-span-4 space-y-2.5 print:hidden">
          <p className="text-xs font-bold uppercase tracking-wider text-secondary px-1">
            Saved Report Archive ({financialAuditReports.length})
          </p>
          {financialAuditReports.length === 0 ? (
            <SectionCard>
              <p className="text-xs text-secondary text-center py-8">
                No saved reports yet. Generate your first Forensic Audit Report above.
              </p>
            </SectionCard>
          ) : (
            financialAuditReports.map((r) => {
              const isSelected = selectedReport?.id === r.id;
              return (
                <div
                  key={r.id}
                  onClick={() => setSelectedReportId(r.id)}
                  className={`p-4 rounded-xl border transition-all cursor-pointer ${
                    isSelected
                      ? 'bg-white border-primary/60 shadow-[0_8px_20px_-8px_rgba(24,114,245,0.22)] ring-1 ring-primary/20'
                      : 'bg-white/75 border-outline-variant/80 hover:bg-white'
                  }`}
                >
                  <div className="flex items-center justify-between gap-2">
                    <span className="text-[11px] font-mono font-bold text-primary">{r.reportCode}</span>
                    <button
                      type="button"
                      onClick={(e) => {
                        e.stopPropagation();
                        deleteFinancialAuditReport(r.id);
                      }}
                      className="p-1 rounded text-secondary hover:text-red-600 hover:bg-red-500/10 cursor-pointer"
                      title="Delete report"
                    >
                      <span className="material-symbols-outlined text-[15px]">delete</span>
                    </button>
                  </div>
                  <p className="text-xs font-bold text-on-surface mt-1 line-clamp-2">{r.title}</p>
                  <p className="text-[11px] text-secondary mt-1">
                    {r.periodLabel} • Health {r.scanSnapshot?.healthScore ?? 100}%
                  </p>
                  <div className="flex items-center justify-between mt-2 text-[11px]">
                    <span className="text-secondary">{r.findingCount} findings</span>
                    <span className="font-data-tabular font-bold text-red-600">
                      {formatNaira(r.totalExposureNaira)}
                    </span>
                  </div>
                </div>
              );
            })
          )}
        </div>

        {/* Executive Forensic Report Document Viewer */}
        <div className="lg:col-span-8 print:col-span-12">
          {!selectedReport ? (
            <SectionCard>
              <p className="text-xs text-secondary text-center py-12">
                Select a saved report from the archive to view, download branded PDF, print, or export CSV.
              </p>
            </SectionCard>
          ) : (
            <div className="rounded-2xl bg-white border border-outline-variant shadow-[0_6px_24px_-8px_rgba(28,41,60,0.08)] overflow-hidden">
              {/* Executive Report Header Banner */}
              <div className="p-5 sm:p-6 bg-gradient-to-r from-blue-600 to-blue-700 text-white">
                <div className="flex flex-col sm:flex-row sm:items-start justify-between gap-4">
                  <div className="space-y-1">
                    <span className="inline-flex items-center gap-1.5 px-2.5 py-0.5 rounded-full text-[10px] font-extrabold uppercase tracking-wider bg-white/15 border border-white/25">
                      {selectedReport.reportCode} • Confidential Forensic Audit
                    </span>
                    <h2 className="text-lg sm:text-xl font-extrabold tracking-tight">{selectedReport.title}</h2>
                    <p className="text-xs text-blue-100">
                      {selectedReport.periodLabel} • Prepared by {selectedReport.generatedBy} on{' '}
                      {new Date(selectedReport.generatedAt).toLocaleString()}
                    </p>
                  </div>

                  {/* Working Export Actions */}
                  <div className="flex items-center gap-2 flex-wrap shrink-0 print:hidden">
                    <button
                      type="button"
                      onClick={() => downloadForensicReportPdf(selectedReport)}
                      className="inline-flex items-center gap-1.5 px-3.5 py-2 rounded-lg bg-white text-blue-700 text-xs font-extrabold hover:bg-blue-50 shadow-sm cursor-pointer"
                    >
                      <span className="material-symbols-outlined text-[16px]">picture_as_pdf</span>
                      Download PDF
                    </button>
                    <button
                      type="button"
                      onClick={() => window.print()}
                      className="inline-flex items-center gap-1.5 px-3 py-2 rounded-lg bg-white/15 text-white border border-white/25 text-xs font-bold hover:bg-white/25 cursor-pointer"
                    >
                      <span className="material-symbols-outlined text-[16px]">print</span>
                      Print
                    </button>
                    <button
                      type="button"
                      onClick={() => handleExportCsv(selectedReport)}
                      className="inline-flex items-center gap-1.5 px-3 py-2 rounded-lg bg-white/15 text-white border border-white/25 text-xs font-bold hover:bg-white/25 cursor-pointer"
                    >
                      <span className="material-symbols-outlined text-[16px]">download</span>
                      CSV
                    </button>
                  </div>
                </div>
              </div>

              <div className="p-5 sm:p-6 space-y-6">
                {/* Executive KPI Summary Strip */}
                <div className="grid grid-cols-2 sm:grid-cols-4 gap-3">
                  <div className="p-3 rounded-xl bg-canvas border border-outline-variant/70">
                    <p className="text-[10px] font-bold uppercase tracking-wider text-secondary">Audit Health</p>
                    <p className="text-lg font-black font-data-tabular text-on-surface mt-0.5">
                      {selectedReport.scanSnapshot?.healthScore ?? 100}%
                    </p>
                    <p className="text-[10px] text-secondary">
                      {selectedReport.criticalCount} crit • {selectedReport.warningCount} warn
                    </p>
                  </div>
                  <div className="p-3 rounded-xl bg-canvas border border-outline-variant/70">
                    <p className="text-[10px] font-bold uppercase tracking-wider text-secondary">Student Inflows</p>
                    <p className="text-lg font-black font-data-tabular text-emerald-700 mt-0.5">
                      {formatNaira(mf?.totalStudentPaymentsReceived || 0)}
                    </p>
                    <p className="text-[10px] text-secondary">Billed: {formatNaira(mf?.totalTuitionBilled || 0)}</p>
                  </div>
                  <div className="p-3 rounded-xl bg-canvas border border-outline-variant/70">
                    <p className="text-[10px] font-bold uppercase tracking-wider text-secondary">Actual Cash</p>
                    <p className="text-lg font-black font-data-tabular text-blue-700 mt-0.5">
                      {formatNaira(mf?.actualCompanyCashTotal || 0)}
                    </p>
                    <p className="text-[10px] text-secondary">Expected: {formatNaira(mf?.expectedNetCashPosition || 0)}</p>
                  </div>
                  <div className="p-3 rounded-xl bg-red-500/[0.06] border border-red-500/25">
                    <p className="text-[10px] font-bold uppercase tracking-wider text-red-700">Master Cash Gap</p>
                    <p className="text-lg font-black font-data-tabular text-red-700 mt-0.5">
                      {cashGap >= 0 ? '+' : '-'}
                      {formatNaira(Math.abs(cashGap))}
                    </p>
                    <p className="text-[10px] text-red-700/80">{cashGap < 0 ? 'Cash Shortfall' : 'Surplus / Balanced'}</p>
                  </div>
                </div>

                {/* 1. Executive Summary */}
                <div className="p-4 rounded-xl bg-canvas/70 border border-outline-variant/70 space-y-2">
                  <h3 className="text-xs font-extrabold uppercase tracking-wider text-on-surface">
                    1. Executive Summary
                  </h3>
                  <p className="text-xs text-on-surface/90 leading-relaxed">{selectedReport.executiveSummary}</p>
                  {selectedReport.aiNarrative && (
                    <div className="pt-2.5 mt-2 border-t border-outline-variant/60">
                      <p className="text-[10px] font-extrabold uppercase tracking-wider text-primary">
                        AI Forensic Narrative
                      </p>
                      <p className="text-xs text-on-surface leading-relaxed mt-1 whitespace-pre-line">
                        {selectedReport.aiNarrative}
                      </p>
                    </div>
                  )}
                </div>

                {/* 2. 5-Layer Money-Flow Reconciliation Table */}
                <div className="space-y-2">
                  <h3 className="text-xs font-extrabold uppercase tracking-wider text-on-surface">
                    2. 5-Layer Money-Flow Reconciliation
                  </h3>
                  <div className="overflow-x-auto rounded-xl border border-outline-variant/80">
                    <table className="w-full text-xs">
                      <thead className="bg-canvas text-secondary uppercase text-[10px]">
                        <tr>
                          <th className="px-3.5 py-2.5 text-left">Layer &amp; Line Item</th>
                          <th className="px-3.5 py-2.5 text-right">Amount (₦)</th>
                        </tr>
                      </thead>
                      <tbody className="divide-y divide-outline-variant/50">
                        {[
                          ['L1 • Tuition Billed (CRM Students)', mf?.totalTuitionBilled || 0, false],
                          ['L1 • Unexempted Course Price Variance Exposure', mf?.coursePriceVarianceTotal || 0, false],
                          ['L2 • Student Payments Received (CRM)', mf?.totalStudentPaymentsReceived || 0, false],
                          ['L2 • Verified Account Inflows (Paystack + Bank Statements)', mf?.totalWalletInflow || 0, false],
                          ['L3 • Mentor Commissions Disbursed', mf?.totalDisbursedToMentors || 0, false],
                          ['L4 • Non-Mentor Business OpEx Paid', mf?.totalNonMentorExpensesPaid || 0, false],
                          ['L5 • Expected Net Cash Position (Inflows − Mentors − OpEx)', mf?.expectedNetCashPosition || 0, true],
                          ['L5 • Actual Company Cash (Paystack + External Banks)', mf?.actualCompanyCashTotal || 0, true],
                          ['L5 • Master Cash Reconciliation Gap (Actual − Expected)', cashGap, true],
                        ].map(([label, val, highlight]) => (
                          <tr key={String(label)} className={highlight ? 'bg-canvas/70 font-bold' : 'hover:bg-canvas/40'}>
                            <td className="px-3.5 py-2.5 text-on-surface">{String(label)}</td>
                            <td
                              className={`px-3.5 py-2.5 text-right font-data-tabular font-bold ${
                                String(label).includes('Gap') && Math.abs(Number(val)) > 100
                                  ? 'text-red-600'
                                  : 'text-on-surface'
                              }`}
                            >
                              {formatNaira(Number(val))}
                            </td>
                          </tr>
                        ))}
                      </tbody>
                    </table>
                  </div>
                </div>

                {/* 3. Company Bank Account Snapshots */}
                {selectedReport.bankSnapshots && selectedReport.bankSnapshots.length > 0 && (
                  <div className="space-y-2">
                    <h3 className="text-xs font-extrabold uppercase tracking-wider text-on-surface">
                      3. Company Bank Account Snapshots ({selectedReport.bankSnapshots.length})
                    </h3>
                    <div className="overflow-x-auto rounded-xl border border-outline-variant/80">
                      <table className="w-full text-xs">
                        <thead className="bg-canvas text-secondary uppercase text-[10px]">
                          <tr>
                            <th className="px-3 py-2 text-left">Bank</th>
                            <th className="px-3 py-2 text-left">NUBAN</th>
                            <th className="px-3 py-2 text-left">Account Name</th>
                            <th className="px-3 py-2 text-left">As-Of Date</th>
                            <th className="px-3 py-2 text-right">Closing Balance</th>
                          </tr>
                        </thead>
                        <tbody className="divide-y divide-outline-variant/50">
                          {selectedReport.bankSnapshots.map((b) => (
                            <tr key={b.id}>
                              <td className="px-3 py-2 font-bold text-on-surface">{b.bankName}</td>
                              <td className="px-3 py-2 font-data-tabular text-secondary">{b.accountNumber}</td>
                              <td className="px-3 py-2 text-on-surface">{b.accountName}</td>
                              <td className="px-3 py-2 font-data-tabular text-secondary">{b.asOfDate}</td>
                              <td className="px-3 py-2 text-right font-data-tabular font-bold text-on-surface">
                                {formatNaira(b.closingBalance)}
                              </td>
                            </tr>
                          ))}
                        </tbody>
                      </table>
                    </div>
                  </div>
                )}

                {/* 4. Paginated Flagged Discrepancies Table */}
                <div className="space-y-2">
                  <div className="flex items-center justify-between gap-2">
                    <h3 className="text-xs font-extrabold uppercase tracking-wider text-on-surface">
                      4. Included Discrepancy Findings ({reportFindings.length})
                    </h3>
                    {reportFindings.length > findingsPageSize && (
                      <div className="flex items-center gap-1.5 text-[11px] print:hidden">
                        <button
                          type="button"
                          disabled={safeFindingsPage <= 1}
                          onClick={() => setFindingsPage((p) => Math.max(1, p - 1))}
                          className="px-2 py-1 rounded border border-outline-variant bg-white font-bold disabled:opacity-40 cursor-pointer"
                        >
                          Prev
                        </button>
                        <span className="font-data-tabular text-secondary">
                          {safeFindingsPage} / {findingsTotalPages}
                        </span>
                        <button
                          type="button"
                          disabled={safeFindingsPage >= findingsTotalPages}
                          onClick={() => setFindingsPage((p) => Math.min(findingsTotalPages, p + 1))}
                          className="px-2 py-1 rounded border border-outline-variant bg-white font-bold disabled:opacity-40 cursor-pointer"
                        >
                          Next
                        </button>
                      </div>
                    )}
                  </div>

                  {reportFindings.length === 0 ? (
                    <p className="text-xs text-secondary">No discrepancies in this report snapshot.</p>
                  ) : (
                    <div className="overflow-x-auto rounded-xl border border-outline-variant/80">
                      <table className="w-full text-xs">
                        <thead className="bg-canvas text-secondary uppercase text-[10px]">
                          <tr>
                            <th className="px-3 py-2 text-left">Layer / Severity</th>
                            <th className="px-3 py-2 text-left">Finding &amp; Diagnosis</th>
                            <th className="px-3 py-2 text-right">Expected</th>
                            <th className="px-3 py-2 text-right">Actual</th>
                            <th className="px-3 py-2 text-right">Delta</th>
                          </tr>
                        </thead>
                        <tbody className="divide-y divide-outline-variant/50">
                          {pagedFindings.map((f) => (
                            <tr key={f.id} className="align-top">
                              <td className="px-3 py-2 whitespace-nowrap">
                                <span
                                  className={`inline-flex px-2 py-0.5 rounded-full text-[10px] font-bold border ${
                                    f.severity === 'Critical'
                                      ? 'bg-red-500/10 text-red-700 border-red-500/20'
                                      : f.severity === 'Warning'
                                        ? 'bg-amber-500/10 text-amber-700 border-amber-500/20'
                                        : 'bg-sky-500/10 text-sky-700 border-sky-500/20'
                                  }`}
                                >
                                  L{f.layer || '-'} • {f.severity}
                                </span>
                              </td>
                              <td className="px-3 py-2">
                                <p className="font-bold text-on-surface">{f.title}</p>
                                <p className="text-[11px] text-secondary mt-0.5">{f.aiDiagnosis}</p>
                              </td>
                              <td className="px-3 py-2 text-right font-data-tabular whitespace-nowrap">
                                {formatNaira(f.expectedAmount)}
                              </td>
                              <td className="px-3 py-2 text-right font-data-tabular whitespace-nowrap">
                                {formatNaira(f.actualAmount)}
                              </td>
                              <td className="px-3 py-2 text-right font-data-tabular font-bold text-red-600 whitespace-nowrap">
                                {formatNaira(f.deltaAmount)}
                              </td>
                            </tr>
                          ))}
                        </tbody>
                      </table>
                    </div>
                  )}
                </div>

                {/* 5. Investigation Cases Snapshot */}
                {selectedReport.casesSnapshot && selectedReport.casesSnapshot.length > 0 && (
                  <div className="space-y-2">
                    <h3 className="text-xs font-extrabold uppercase tracking-wider text-on-surface">
                      5. Investigation Cases &amp; User Responses ({selectedReport.casesSnapshot.length})
                    </h3>
                    <div className="space-y-2">
                      {selectedReport.casesSnapshot.map((c) => (
                        <div key={c.id} className="p-3 rounded-xl border border-outline-variant/70 bg-canvas/50 text-xs space-y-1">
                          <div className="flex items-center justify-between gap-2">
                            <span className="font-bold text-on-surface">
                              {c.caseNumber}: {c.title}
                            </span>
                            <span className="text-[11px] font-bold text-primary">{c.status}</span>
                          </div>
                          {c.queries.map((q) => (
                            <p key={q.id} className="text-[11px] text-secondary">
                              • <strong>{q.targetUserName}</strong>:{' '}
                              {q.responseText ? `Answered — "${q.responseText}"` : 'Pending response'}
                            </p>
                          ))}
                        </div>
                      ))}
                    </div>
                  </div>
                )}
              </div>
            </div>
          )}
        </div>
      </div>
    </div>
  );
};
